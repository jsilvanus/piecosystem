#!/usr/bin/env bash
# pi-restore.sh: put the files of a pi-backup.sh bundle back on a fresh card and write
# rebuild-steps.sh (packages, repos, units) for the operator to read and run.
# Default is a dry run; --apply writes files. It never runs rebuild-steps.sh itself.
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: pi-restore.sh BUNDLE [options]
  BUNDLE               a .tar.age (needs --identity) or an already decrypted .tar
  --identity FILE      age private key
  --apply              write the files (default: only show what would change)
  --only user|system   restore only files under the user's home (user) or everything else (system)
  --steps FILE         where to write rebuild-steps.sh; default ./rebuild-steps.sh
  --root DIR           prefix for every path (tests); default /
EOF
}

bundle=""; identity=""; apply=0; only=""; steps="./rebuild-steps.sh"; root="/"
while [ $# -gt 0 ]; do
  case "$1" in
    --identity) identity="$2"; shift ;;
    --apply) apply=1 ;;
    --only) only="$2"; shift ;;
    --steps) steps="$2"; shift ;;
    --root) root="$2"; shift ;;
    -h|--help) usage; exit 0 ;;
    -*) echo "pi-restore: unknown option $1" >&2; usage >&2; exit 2 ;;
    *) bundle="$1" ;;
  esac
  shift
done
root="${root%/}"
[ -n "$bundle" ] && [ -f "$bundle" ] || { echo "pi-restore: bundle not found" >&2; usage >&2; exit 2; }
case "$only" in ""|user|system) ;; *) echo "pi-restore: --only user|system" >&2; exit 2 ;; esac

umask 077
stage="$(mktemp -d)"; trap 'rm -rf "$stage"' EXIT
case "$bundle" in
  *.age)
    [ -n "$identity" ] || { echo "pi-restore: an .age bundle needs --identity" >&2; exit 2; }
    age -d -i "$identity" "$bundle" | tar -xf - --numeric-owner -C "$stage" ;;
  *) tar -xf "$bundle" --numeric-owner -C "$stage" ;;
esac
meta="$stage/.pi-backup"
[ -f "$meta/info.txt" ] || { echo "pi-restore: not a pi-backup bundle (no .pi-backup/info.txt)" >&2; exit 2; }
home="$(sed -n 's/^home=//p' "$meta/info.txt")"
user="$(sed -n 's/^user=//p' "$meta/info.txt")"
echo "bundle: $(tr '\n' ' ' < "$meta/info.txt")"

new=0; changed=0; same=0
while IFS= read -r -d '' f; do
  rel="${f#"$stage"/}"
  case "$rel" in .pi-backup/*) continue ;; esac
  case "/$rel" in "$home"/*) part=user ;; *) part=system ;; esac
  [ -z "$only" ] || [ "$only" = "$part" ] || continue
  target="$root/$rel"
  if [ ! -e "$target" ] && [ ! -L "$target" ]; then state=new; new=$((new + 1))
  elif cmp -s "$f" "$target"; then state=same; same=$((same + 1))
  else state=changed; changed=$((changed + 1)); fi
  printf '%-8s /%s\n' "$state" "$rel"
  if [ "$apply" = 1 ] && [ "$state" != same ]; then
    mkdir -p "$(dirname "$target")"
    [ "$state" = changed ] && cp -a -- "$target" "$target.pre-restore"
    cp -a -- "$f" "$target"
  fi
done < <(find "$stage" \( -type f -o -type l \) -print0 | sort -z)
echo "new $new, changed $changed, same $same$([ "$apply" = 1 ] && echo ' (written; changed files kept as *.pre-restore)' || echo ' (dry run, nothing written)')"

# rebuild-steps.sh: everything that is not a file. Remote URLs lose any user:token part.
q() { printf '%q' "$1"; }
{
  echo '#!/usr/bin/env bash'
  echo "# Generated by pi-restore.sh from $(basename "$bundle") on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo '# Read it before running. Devices deploy from main only: repos are cloned at main, the'
  echo '# backed-up commit is noted for comparison.'
  echo 'set -euo pipefail'
  echo
  echo '# 1. Packages that were installed by hand'
  if [ -s "$meta/apt-manual.txt" ]; then
    echo 'sudo apt-get update'
    printf 'sudo apt-get install -y'; while read -r p; do [ -n "$p" ] && printf ' %s' "$(q "$p")"; done < "$meta/apt-manual.txt"; echo
  else echo '# (no package list in the bundle)'; fi
  echo
  echo '# 2. Node and pnpm, as before:'
  if [ -s "$meta/versions.txt" ]; then grep -E '^(node|pnpm) ' "$meta/versions.txt" | sed 's/^/#   /'; else echo '#   (versions not recorded)'; fi
  echo '#   install them the way piecosystem deploy docs describe, then continue.'
  echo
  echo '# 3. Repos (then install and build each one as its README says)'
  echo "mkdir -p $(q "$home/apps")"
  while IFS=$'\t' read -r name url branch commit; do
    [ -n "$name" ] || continue
    url="$(printf '%s' "$url" | sed -E 's#^(https?://)[^/@]+@#\1#')"
    dir="$home/apps/$name"
    echo "[ -d $(q "$dir/.git") ] || git clone -b main $(q "$url") $(q "$dir")   # backed up at $branch $commit"
  done < "$meta/repos.tsv"
  echo
  echo '# 4. User services'
  echo 'systemctl --user daemon-reload'
  if [ -s "$meta/systemd-user-enabled.txt" ]; then
    awk '{print $1}' "$meta/systemd-user-enabled.txt" | while read -r u; do [ -n "$u" ] && echo "systemctl --user enable $(q "$u")"; done
  else
    for f in "$stage$home"/.config/systemd/user/*.service "$stage$home"/.config/systemd/user/*.timer; do
      [ -e "$f" ] && echo "systemctl --user enable $(q "$(basename "$f")")"
    done
  fi
  if grep -q 'Linger=yes' "$meta/linger.txt" 2>/dev/null || [ ! -s "$meta/linger.txt" ]; then echo "sudo loginctl enable-linger $(q "$user")"; fi
  echo
  echo '# 5. System services that were enabled (check before enabling)'
  if [ -s "$meta/systemd-system-enabled.txt" ]; then awk '{print "# sudo systemctl enable " $1}' "$meta/systemd-system-enabled.txt"; else echo '# (not recorded: user-only bundle)'; fi
  if [ -s "$meta/users.txt" ]; then echo; echo '# 6. Users (name:uid:home:shell:groups); create missing ones before restoring their files'; sed 's/^/# /' "$meta/users.txt"; fi
} > "$steps"
chmod 700 "$steps"
echo "wrote $steps"
